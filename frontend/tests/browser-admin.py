"""Admin UI sandbox checks. Auth is intercepted; no backend writes occur."""
import os
import re
from pathlib import Path
from playwright.sync_api import sync_playwright, expect
base = os.environ.get('KIX_TEST_BASE_URL','http://127.0.0.1:5177')
artifacts = Path(os.environ.get('KIX_TEST_ARTIFACTS','/private/tmp/kix-admin-artifacts'))
artifacts.mkdir(parents=True,exist_ok=True)
with sync_playwright() as p:
    browser=p.chromium.launch(headless=True)
    page=browser.new_page(viewport={'width':1280,'height':900})
    errors=[];api_requests=[]
    page.on('pageerror',lambda error:errors.append(str(error)))
    def api(route):
        url=route.request.url;api_requests.append(url)
        if url.endswith('/auth/login'):
            role='admin' if route.request.post_data_json['email'].startswith('admin') else 'user'
            route.fulfill(json={'accessToken':'ui-test-'+role,'tokenType':'Bearer','expiresIn':3600})
        elif url.endswith('/members/me'):
            role='ADMIN' if route.request.headers.get('authorization','').endswith('admin') else 'USER'
            route.fulfill(json={'id':'101','role':role})
        else:route.abort()
    page.route(base+'/api/**',api)
    def login(email):
        page.get_by_label('이메일',exact=True).fill(email)
        page.get_by_label('비밀번호',exact=True).fill('ui-test-password')
        page.get_by_role('button',name='로그인',exact=True).click()
    page.goto(base+'/admin/products/new');page.wait_for_load_state('networkidle')
    expect(page).to_have_url(re.compile('/login$'))
    login('user@example.com')
    expect(page.get_by_role('alert')).to_contain_text('접근 권한이 없습니다.')
    expect(page.get_by_role('link',name='관리자',exact=True)).to_have_count(0)
    page.get_by_role('button',name='로그아웃',exact=True).click()
    login('admin@example.com')
    expect(page.get_by_role('heading',name='샘플 상품 등록')).to_be_visible()
    page.get_by_label('상품명',exact=True).fill('관리자 신규 샘플')
    page.get_by_label('상품 브랜드',exact=True).select_option('STUDIO SAMPLE')
    page.get_by_label('가격 (원)',exact=True).fill('123000')
    page.get_by_label('상품 판매 상태',exact=True).select_option('STOPPED')
    page.get_by_label('설명',exact=True).fill('관리자 샘플 설명')
    page.get_by_label('사이즈 (mm) 옵션 1',exact=True).fill('250')
    page.get_by_label('재고 옵션 1',exact=True).fill('2')
    page.get_by_role('button',name='사이즈 옵션 추가',exact=True).click()
    page.get_by_label('사이즈 (mm) 옵션 2',exact=True).fill('250')
    page.get_by_role('button',name='샘플 등록 저장',exact=True).click()
    expect(page.get_by_role('alert')).to_contain_text('같은 사이즈')
    page.get_by_label('사이즈 (mm) 옵션 2',exact=True).fill('260')
    page.get_by_role('button',name='샘플 등록 저장',exact=True).click()
    expect(page.get_by_role('heading',name='샘플 상품 수정')).to_be_visible()
    created_id=page.url.split('/products/')[1].split('/')[0]
    expect(page.get_by_role('status')).to_contain_text('샘플 상품을 등록했습니다.')
    expect(page.get_by_label('상품명',exact=True)).to_have_value('관리자 신규 샘플')
    expect(page.get_by_label('재고 옵션 2',exact=True)).to_have_value('0')
    for width in [390,320]:
        page.set_viewport_size({'width':width,'height':850})
        assert page.evaluate('document.documentElement.scrollWidth <= innerWidth'),width
    page.screenshot(path=str(artifacts/'editor-mobile.png'),full_page=True)
    page.get_by_label('가격 (원)',exact=True).fill('133000')
    page.get_by_label('재고 옵션 1',exact=True).fill('5')
    page.get_by_role('button',name='옵션 2 제거',exact=True).click()
    expect(page.get_by_role('button',name='옵션 1 제거',exact=True)).to_be_disabled()
    page.get_by_role('button',name='사이즈 옵션 추가',exact=True).click()
    page.get_by_label('사이즈 (mm) 옵션 2',exact=True).fill('270')
    page.get_by_label('재고 옵션 2',exact=True).fill('1')
    page.get_by_label('상품 판매 상태',exact=True).select_option('ON_SALE')
    page.get_by_role('button',name='샘플 수정 저장',exact=True).click()
    expect(page.get_by_role('heading',name='관리자 샘플 상품')).to_be_visible()
    page.get_by_label('관리자 상품 검색',exact=True).fill('관리자 신규')
    page.get_by_role('button',name='필터 적용',exact=True).click()
    expect(page.locator('main li')).to_have_count(1)
    expect(page.locator('main li')).to_contain_text('133,000원 · 옵션 2개 · 총 재고 6개')
    assert page.evaluate('document.documentElement.scrollWidth <= innerWidth')
    page.get_by_role('button',name='관리자 신규 샘플 삭제',exact=True).click()
    expect(page.get_by_role('dialog',name='샘플 상품 삭제 확인')).to_be_visible()
    box=page.get_by_role('dialog').bounding_box()
    assert box['x'] >= 15 and box['width'] <= 290,box
    page.screenshot(path=str(artifacts/'delete-mobile.png'),full_page=True)
    assert page.evaluate('document.documentElement.scrollWidth <= innerWidth')
    page.keyboard.press('Escape')
    expect(page.get_by_role('dialog')).not_to_be_visible()
    expect(page.locator('main li')).to_have_count(1)
    page.get_by_role('button',name='관리자 신규 샘플 삭제',exact=True).click()
    page.get_by_role('button',name='샘플 삭제 확인',exact=True).click()
    expect(page.get_by_text('조건에 맞는 샘플 상품이 없습니다.',exact=True)).to_be_visible()
    page.evaluate('(path) => { history.pushState({}, "", path); dispatchEvent(new PopStateEvent("popstate")); }','/admin/products/'+created_id+'/edit')
    expect(page.get_by_role('alert')).to_contain_text('관리자 샘플 상품을 찾을 수 없습니다.')
    page.get_by_role('link',name='관리자 목록으로',exact=True).click()
    expect(page.locator('main li')).to_have_count(8)
    page.get_by_role('button',name='다음',exact=True).click()
    expect(page.locator('main li')).to_have_count(2)
    page.get_by_label('판매 상태 필터',exact=True).select_option('STOPPED')
    page.get_by_role('button',name='필터 적용',exact=True).click()
    expect(page.locator('main li')).to_have_count(1)
    page.get_by_role('link',name='초기화',exact=True).click()
    page.get_by_role('link',name='로우 스니커즈 샘플 수정',exact=True).click()
    page.get_by_label('가격 (원)',exact=True).fill('9999')
    page.get_by_role('button',name='샘플 수정 저장',exact=True).click()
    expect(page.locator('main li').first).to_contain_text('9,999원')
    page.get_by_role('link',name='상품 탐색',exact=True).click()
    expect(page.locator('article').first).to_contain_text('139,000원')
    page.get_by_role('link',name='관리자',exact=True).click()
    expect(page.locator('main li').first).to_contain_text('139,000원')
    page.screenshot(path=str(artifacts/'list-mobile.png'),full_page=True)
    page.get_by_role('button',name='로그아웃',exact=True).click()
    expect(page).to_have_url(re.compile('/login$'))
    assert all('/auth/login' in url or '/members/me' in url for url in api_requests),api_requests
    assert page.evaluate('localStorage.length === 0 && sessionStorage.length === 0')
    assert not errors,errors
    print('PASS: guest/USER/ADMIN access, create/edit/options/stock, duplicate size, modal cancel/delete, deleted 404, search/status/paging, mobile 390/320, sandbox reset/public isolation; no page errors or admin API writes')
    browser.close()
