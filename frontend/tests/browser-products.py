from playwright.sync_api import sync_playwright, expect
import re
import os
from pathlib import Path
artifacts = Path(os.environ.get("KIX_TEST_ARTIFACTS", "/private/tmp/kix-browser-artifacts"))
artifacts.mkdir(parents=True, exist_ok=True)
with sync_playwright() as p:
    browser = p.chromium.launch(headless=True)
    page = browser.new_page(viewport={'width':1440,'height':1000})
    errors=[]
    page.on('pageerror', lambda error: errors.append(str(error)))
    base=os.environ.get('KIX_TEST_BASE_URL','http://127.0.0.1:5174')
    page.goto(base+'/products'); page.wait_for_load_state('networkidle')
    expect(page.locator('article')).to_have_count(8)
    page.get_by_role('button',name='다음',exact=True).click()
    expect(page.locator('article')).to_have_count(2)
    expect(page).to_have_url(re.compile('page=1'))
    page.get_by_label('브랜드',exact=True).select_option('STUDIO SAMPLE')
    page.get_by_role('button',name='검색 적용').click()
    expect(page.locator('article')).to_have_count(5)
    assert 'page=' not in page.url
    page.get_by_placeholder('상품명 또는 브랜드').fill('없는상품')
    page.get_by_role('button',name='검색 적용').click()
    expect(page.get_by_text('검색 결과가 없습니다.',exact=False)).to_be_visible()
    page.get_by_role('link',name='초기화',exact=True).click()
    expect(page.locator('article')).to_have_count(8)
    page.locator('article a').nth(1).click()
    expect(page.get_by_role('heading',level=1)).to_have_text('하이 스니커즈 샘플')
    expect(page.get_by_role('button',name='260 품절')).to_be_disabled()
    page.get_by_role('button',name='275 3개 남음').click()
    expect(page.get_by_role('button',name='275 3개 남음')).to_have_attribute('aria-pressed','true')
    page.get_by_role('button',name='수량 늘리기').click()
    page.get_by_role('button',name='수량 늘리기').click()
    expect(page.get_by_role('button',name='수량 늘리기')).to_be_disabled()
    expect(page.get_by_label('선택 수량')).to_have_text('3')
    page.get_by_role('button',name='250 1개 남음').click()
    expect(page.get_by_label('선택 수량')).to_have_text('1')
    expect(page.get_by_role('button',name='샘플 주문 확인')).to_be_enabled()
    page.screenshot(path=str(artifacts/'detail-desktop.png'),full_page=True)
    for width,cols in [(1440,4),(800,3),(390,2),(320,2)]:
        page.set_viewport_size({'width':width,'height':850})
        page.goto(base+'/products'); page.wait_for_load_state('networkidle')
        grid=page.locator('article').first.locator('..')
        count=grid.evaluate('(element) => getComputedStyle(element).gridTemplateColumns.split(" ").length')
        assert count==cols, (width,count)
        assert page.evaluate('document.documentElement.scrollWidth <= innerWidth'),width
        page.goto(base+'/products/sample-2'); page.wait_for_load_state('networkidle')
        assert page.evaluate('document.documentElement.scrollWidth <= innerWidth'),width
        if width==390: page.screenshot(path=str(artifacts/'detail-mobile.png'),full_page=True)
    page.goto(base+'/products/sample-4'); page.wait_for_load_state('networkidle')
    expect(page.get_by_text('모든 사이즈가 품절되었습니다.',exact=True)).to_be_visible()
    expect(page.locator('fieldset button:enabled')).to_have_count(0)
    page.goto(base+'/products/sample-9'); page.wait_for_load_state('networkidle')
    expect(page.get_by_text('판매가 중지된 상품입니다.',exact=True)).to_be_visible()
    expect(page.locator('fieldset button:enabled')).to_have_count(0)
    page.goto(base+'/products/unknown'); page.wait_for_load_state('networkidle')
    expect(page.get_by_role('alert')).to_contain_text('상품을 찾을 수 없습니다.')
    page.goto(base+'/my'); page.wait_for_load_state('networkidle')
    expect(page).to_have_url(re.compile('/login$'))
    page.goto(base+'/products?page=Infinity'); page.wait_for_load_state('networkidle')
    expect(page.locator('article')).to_have_count(8)
    page.goto(base+'/products?page=999'); page.wait_for_load_state('networkidle')
    expect(page.locator('article')).to_have_count(2)
    page.get_by_role('button',name='이전',exact=True).click()
    expect(page.locator('article')).to_have_count(8)
    assert not errors,errors
    print('PASS: search/filter/paging/reset/detail/stock/quantity/disabled purchase/404/auth redirect/responsive 4-3-2 grid; no page errors')
    browser.close()
